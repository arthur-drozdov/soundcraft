"""Sampler instrument writers: SFZ and DecentSampler, plus keybed planning."""

from __future__ import annotations

import math
import os
import xml.etree.ElementTree as ET
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any, TypedDict

from .wav import atomic_write_bytes

MAX_ZONES = 4096
LOOP_MODES = ("no_loop", "one_shot", "loop_continuous", "loop_sustain")
_LOOPING = ("loop_continuous", "loop_sustain")


class Zone(TypedDict, total=False):
    """A sample zone. ``sample``, ``root_note``, ``key_low`` and ``key_high`` are required."""

    sample: str
    root_note: int
    key_low: int
    key_high: int
    vel_low: int
    vel_high: int
    tune_cents: float
    gain_db: float
    loop_mode: str
    loop_start: int
    loop_end: int


class InstrumentError(ValueError):
    """Raised for invalid zones or paths."""


def _int_in(zone: Mapping[str, Any], key: str, lo: int, hi: int, default: int | None = None) -> int:
    value = zone.get(key, default)
    if isinstance(value, bool) or not isinstance(value, int) or not lo <= value <= hi:
        raise InstrumentError(f"zone {key} must be an integer in {lo}..{hi}, got {value!r}")
    return value


def _num(zone: Mapping[str, Any], key: str, limit: float) -> float:
    value = zone.get(key, 0.0)
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value) or abs(value) > limit:
        raise InstrumentError(f"zone {key} must be a finite number within +/-{limit}, got {value!r}")
    return float(value)


def _validate(zone: Mapping[str, Any]) -> dict[str, Any]:
    sample = zone.get("sample")
    if not isinstance(sample, str) or not sample or len(sample) > 512 or any(ord(c) < 32 for c in sample):
        raise InstrumentError("zone sample must be a non-empty path without control characters")
    clean: dict[str, Any] = {
        "sample": sample,
        "root_note": _int_in(zone, "root_note", 0, 127),
        "key_low": _int_in(zone, "key_low", 0, 127),
        "key_high": _int_in(zone, "key_high", 0, 127),
        "vel_low": _int_in(zone, "vel_low", 0, 127, 0),
        "vel_high": _int_in(zone, "vel_high", 0, 127, 127),
        "tune_cents": _num(zone, "tune_cents", 1200.0),
        "gain_db": _num(zone, "gain_db", 96.0),
        "loop_mode": zone.get("loop_mode"),
    }
    if clean["key_low"] > clean["key_high"] or clean["vel_low"] > clean["vel_high"]:
        raise InstrumentError("zone ranges must have low <= high")
    if clean["loop_mode"] is not None and clean["loop_mode"] not in LOOP_MODES:
        raise InstrumentError(f"loop_mode must be one of {LOOP_MODES}")
    for key in ("loop_start", "loop_end"):
        clean[key] = _int_in(zone, key, 0, 2**31 - 1) if zone.get(key) is not None else None
    if clean["loop_start"] is not None and clean["loop_end"] is not None and clean["loop_end"] <= clean["loop_start"]:
        raise InstrumentError("loop_end must be greater than loop_start")
    return clean


def _prepare(zones: Sequence[Mapping[str, Any]], path: str | os.PathLike[str], sample_dir: str | os.PathLike[str]) -> list[dict[str, Any]]:
    if not zones:
        raise InstrumentError("at least one zone is required")
    if len(zones) > MAX_ZONES:
        raise InstrumentError(f"too many zones (cap {MAX_ZONES})")
    out_dir = Path(os.path.abspath(path)).parent
    prepared = []
    for zone in zones:
        clean = _validate(zone)
        sample_path = Path(os.path.abspath(Path(sample_dir) / clean["sample"]))
        rel = Path(os.path.relpath(sample_path, out_dir)).as_posix()
        if any(c in rel for c in "\r\n\t"):
            raise InstrumentError("sample path contains control characters")
        clean["path"] = rel
        prepared.append(clean)
    return prepared


def write_sfz(path: str | os.PathLike[str], zones: Sequence[Mapping[str, Any]], sample_dir: str | os.PathLike[str]) -> None:
    """Write an SFZ with one ``<region>`` per zone. ``sample=`` is written relative to the SFZ's folder,
    resolving each zone's ``sample`` against ``sample_dir``."""
    lines = ["// generated by audiokit", "<group>"]
    for z in _prepare(zones, path, sample_dir):
        lines += ["<region>", f"sample={z['path']}", f"pitch_keycenter={z['root_note']}"]
        lines += [f"lokey={z['key_low']}", f"hikey={z['key_high']}", f"lovel={z['vel_low']}", f"hivel={z['vel_high']}"]
        if z["tune_cents"]:
            lines.append(f"tune={z['tune_cents']:g}")
        if z["gain_db"]:
            lines.append(f"volume={z['gain_db']:g}")
        if z["loop_mode"]:
            lines.append(f"loop_mode={z['loop_mode']}")
        if z["loop_start"] is not None:
            lines.append(f"loop_start={z['loop_start']}")
        if z["loop_end"] is not None:
            lines.append(f"loop_end={z['loop_end']}")
    atomic_write_bytes(path, ("\n".join(lines) + "\n").encode("utf-8"))


def write_dspreset(path: str | os.PathLike[str], zones: Sequence[Mapping[str, Any]], sample_dir: str | os.PathLike[str]) -> None:
    """Write a DecentSampler ``.dspreset`` with one ``<sample>`` per zone (tuning in semitones, volume in dB)."""
    root = ET.Element("DecentSampler", {"minVersion": "1.0.0"})
    group = ET.SubElement(ET.SubElement(root, "groups"), "group")
    for z in _prepare(zones, path, sample_dir):
        attrs = {
            "path": z["path"],
            "rootNote": str(z["root_note"]),
            "loNote": str(z["key_low"]),
            "hiNote": str(z["key_high"]),
            "loVel": str(z["vel_low"]),
            "hiVel": str(z["vel_high"]),
            "tuning": f"{z['tune_cents'] / 100.0:g}",
            "volume": f"{z['gain_db']:g}dB",
        }
        if z["loop_mode"] in _LOOPING:
            attrs["loopEnabled"] = "true"
            if z["loop_start"] is not None:
                attrs["loopStart"] = str(z["loop_start"])
            if z["loop_end"] is not None:
                attrs["loopEnd"] = str(z["loop_end"])
        ET.SubElement(group, "sample", attrs)
    ET.indent(root)
    atomic_write_bytes(path, ET.tostring(root, encoding="utf-8", xml_declaration=True) + b"\n")


def plan_keybed(low: int, high: int, step: int) -> list[tuple[int, int, int]]:
    """Plan sample zones over keys ``low..high``: ``[(root, key_low, key_high), ...]``.

    Keys are split into consecutive groups of ``step`` (the last may be shorter), so every key is
    covered exactly once; each group's root is its middle key."""
    for name, value, lo, hi in (("low", low, 0, 127), ("high", high, 0, 127), ("step", step, 1, 128)):
        if isinstance(value, bool) or not isinstance(value, int) or not lo <= value <= hi:
            raise InstrumentError(f"{name} must be an integer in {lo}..{hi}")
    if low > high:
        raise InstrumentError("low must be <= high")
    plan = []
    for first in range(low, high + 1, step):
        last = min(first + step - 1, high)
        plan.append((first + (last - first) // 2, first, last))
    return plan


__all__ = ["Zone", "InstrumentError", "LOOP_MODES", "write_sfz", "write_dspreset", "plan_keybed"]
